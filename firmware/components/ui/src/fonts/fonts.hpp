#pragma GCC diagnostic ignored "-Wundef"
#pragma GCC diagnostic ignored "-Wconversion"
#pragma GCC diagnostic ignored "-Wsign-conversion"
#include "lvgl.h"
#pragma GCC diagnostic pop

#include "theme/tokens.hpp"

// The generated Inter faces — Architecture Spec §5.12 `ui_assets`, Production UI
// Specification §4.
//
// INTERNAL HEADER of the ui component. It names LVGL types, so it lives under src/
// and is not on the public include path (Bootstrap Spec §5.1).
//
// The six faces are committed C sources generated by tools/generate-fonts.py from
// the Inter weights vendored at assets/fonts/inter/, with `tnum` frozen into the
// character map so every digit shares one advance width. Provenance, licence and
// the Reserved Font Name finding are in assets/fonts/inter/PROVENANCE.md.
//
// A face is selected by §4 text role, never by size and weight separately. The
// pairing is what §4 specifies, and choosing them independently at a use site is
// how screen-specific typography gets introduced (§2 prohibits it).

namespace prd::ui::fonts {

// The face for a §4 text role. Never null: an unhandled role returns the body face
// rather than a null pointer, because a missing font in LVGL is a crash inside the
// draw path and a wrong-sized label is a visible defect that can be reported.
[[nodiscard]] const lv_font_t* for_role(theme::TextRole role);

// Result of the start-up tabular-figure check.
//
// WHY THIS EXISTS. The whole reason Production UI §4 requires tabular figures is
// that a value must not shift as it counts. Whether the generated bitmaps actually
// have that property is a fact about 222 kB of generated C, and no host test can
// see it: the host build compiles no LVGL. So it is measured on the device at
// start-up, once, and reported — a comment claiming tabular figures would be a
// claim, and this is a measurement.
struct DigitMetrics {
    // Advance width shared by all ten digits, in pixels, per face.
    std::uint16_t advance{0};

    // Set when the ten digits do NOT share one advance width, which means the
    // generated face is proportional and §4 is not satisfied.
    bool uniform{false};

    // Widest and narrowest observed, so a failure reports how far off it is rather
    // than only that it failed.
    std::uint16_t minimum{0};
    std::uint16_t maximum{0};
};

[[nodiscard]] DigitMetrics digit_metrics(const lv_font_t* font);

// Checks every face and logs one line per face under the prd.ui tag. Render task only,
// after lv_init().
//
// Returns false if any face has non-uniform digit widths (§4's tabular requirement) OR is
// taller than the line height its §4 text role reserves. Both are properties of 300 kB of
// generated C that no host test can see, because the host build compiles no LVGL.
[[nodiscard]] bool verify();

// Where a glyph's INK sits, as opposed to where its box sits.
//
// Optical alignment needs this and box arithmetic cannot supply it. A baseline-aligned pair
// of glyphs from faces of different sizes has aligned boxes by construction, and can still
// look wrong: what the eye aligns is ink. LVGL reports each glyph's height and its offset
// from the baseline, which together give the ink's extent.
//
// `top` and `bottom` are measured downward from the top of the label's line box, so they can
// be compared directly against the positions in the layout report.
struct InkExtent {
    bool known{false};
    std::int32_t top{0};
    std::int32_t bottom{0};
    std::int32_t height{0};
};

[[nodiscard]] InkExtent ink_extent(const lv_font_t* font, std::uint32_t letter);

} // namespace prd::ui::fonts
